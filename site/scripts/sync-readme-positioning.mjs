/**
 * Sync the canonical positioning block from site/src/lib/positioning.json into
 * the root README.md.
 *
 * Only the marker-delimited block between
 *   <!-- BEGIN POSITIONING ... -->
 *   <!-- END POSITIONING -->
 * is replaced; everything else in the README is preserved byte-for-byte.
 *
 * Deliberately NOT part of prepare:site — a build must never mutate the README.
 * Run it explicitly, or via `npm --prefix site run sync:readme-positioning`.
 *
 * Env override: CHUNKHOUND_ROOT — set to repo root for hermetic testing.
 * Mode: pass --check to exit non-zero on drift without writing (CI / tests).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { loadPositioning, repoRoot } from "./lib/repo-context.mjs";

const root = repoRoot();

const POSITIONING_FILE = resolve(root, "site/src/lib/positioning.json");
const README_FILE = resolve(root, "README.md");

const BEGIN_MARKER =
  "<!-- BEGIN POSITIONING: generated by site/scripts/sync-readme-positioning.mjs from site/src/lib/positioning.json -->";
const END_MARKER = "<!-- END POSITIONING -->";

// Only the fields rendered into the README block below. positioning.json's
// other fields are validated by their own consumers (Base/Hero/Community
// components, generate-llms-txt.mjs).
const REQUIRED_FIELDS = ["headline", "subheadline", "amplifier"];
const CHECK_MODE = process.argv.includes("--check");

// Count non-overlapping occurrences of a marker, so duplicate blocks are
// rejected instead of silently syncing only the first pair.
function countOccurrences(haystack, needle) {
  let count = 0;
  for (let pos = haystack.indexOf(needle); pos !== -1; pos = haystack.indexOf(needle, pos + needle.length)) {
    count += 1;
  }
  return count;
}

// positioning.json copy is interpolated into README HTML. Escape `&`, `<`, `>`
// so a field can neither inject markup nor forge the END marker via `-->` and
// corrupt the marker-delimited block.
function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

const positioning = loadPositioning(root, REQUIRED_FIELDS);

const readme = readFileSync(README_FILE, "utf-8");
const beginCount = countOccurrences(readme, BEGIN_MARKER);
const endCount = countOccurrences(readme, END_MARKER);
if (beginCount === 0 || endCount === 0) {
  throw new Error(
    `README.md is missing the positioning markers (${BEGIN_MARKER} / ${END_MARKER}). ` +
      "Add them around the block to sync, then re-run."
  );
}
if (beginCount !== 1 || endCount !== 1) {
  throw new Error(
    `README.md must contain exactly one positioning marker pair (found ${beginCount} ` +
      `BEGIN, ${endCount} END). Remove the duplicates, then re-run.`
  );
}
const beginIdx = readme.indexOf(BEGIN_MARKER);
const endIdx = readme.indexOf(END_MARKER);
if (endIdx <= beginIdx) {
  throw new Error(
    "README.md markers are out of order: END marker must follow BEGIN marker."
  );
}

const body = [
  '<p align="center">',
  `  <strong>${escapeHtml(positioning.headline)}</strong>`,
  "</p>",
  "",
  '<p align="center">',
  `  ${escapeHtml(positioning.subheadline)}`,
  "</p>",
  "",
  '<p align="center">',
  `  ${escapeHtml(positioning.amplifier)}`,
  "</p>",
].join("\n");
const generated = `${BEGIN_MARKER}\n${body}\n${END_MARKER}`;
const updated =
  readme.slice(0, beginIdx) +
  generated +
  readme.slice(endIdx + END_MARKER.length);

if (CHECK_MODE) {
  if (updated === readme) {
    console.log("\u2713 README positioning block is in sync");
    process.exit(0);
  }
  console.error(
    "\u2717 README positioning block is out of sync \u2014 run `npm --prefix site run sync:readme-positioning`"
  );
  process.exit(1);
}

writeFileSync(README_FILE, updated);
console.log(`\u2713 Synced README positioning block from ${POSITIONING_FILE}`);
